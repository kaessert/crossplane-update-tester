// TestMergePatchSiblingKeySet covers the helper in isolation: the two
// preconditions (value: is an object patch, and the field already holds an
// object at create time) both gating an empty result when either fails.
func TestMergePatchSiblingKeySet(t *testing.T) {
	cases := map[string]struct {
		reason      string
		forProvider map[string]interface{}
		test        manifest.UpdateTest
		want        []string
	}{
		"ObjectPatchOntoPopulatedObject": {
			reason: "the ordinary sibling-survival shape",
			forProvider: map[string]interface{}{
				"bodyMatcher": map[string]interface{}{
					"exactValues": []interface{}{},
					"regexValues": []interface{}{},
				},
			},
			test: manifest.UpdateTest{
				Field: "bodyMatcher",
				Value: map[string]interface{}{"exactValues": []interface{}{"updated"}},
			},
			want: []string{"regexValues"},
		},
		"ListValuePatch": {
			reason: "a list-valued patch never gates a sibling set — RFC 7386 replaces it wholesale",
			forProvider: map[string]interface{}{
				"bodyMatcher": map[string]interface{}{"exactValues": []interface{}{}},
			},
			test: manifest.UpdateTest{
				Field: "bodyMatcher",
				Value: []interface{}{"updated"},
			},
			want: nil,
		},
		"FieldAbsentFromForProvider": {
			reason: "a first-time-set field has nothing for the merge-patch simulation to see",
			forProvider: map[string]interface{}{
				"description": "original",
			},
			test: manifest.UpdateTest{
				Field: "domainMatcher",
				Value: map[string]interface{}{"exactValues": []interface{}{"example.com"}},
			},
			want: nil,
		},
	}

	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got := mergePatchSiblingKeySet(tc.forProvider, tc.test)
			var gotKeys []string
			for k := range got {
				gotKeys = append(gotKeys, k)
			}
			sort.Strings(gotKeys)
			want := append([]string(nil), tc.want...)
			sort.Strings(want)
			if !reflect.DeepEqual(gotKeys, want) {
				t.Errorf("%s: mergePatchSiblingKeySet() keys = %v, want %v", tc.reason, gotKeys, want)
			}
		})
	}
}

