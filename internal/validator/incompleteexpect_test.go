// matcherTypesSrc exercises the SPLIT layout — a distinct
// "<Type>Observation" companion struct — via the fast path in
// resolveObservationFieldsForKindField. It intentionally declares
// PolicyMatcherTypeBasicObservation as a SEPARATE struct from
// PolicyMatcherTypeBasic to pin that fast path; provider-f5xc's REAL
// ServicePolicyRuleParameters.DomainMatcher does not have a separate
