// gadgetTypesSrc is a synthetic generated-types fixture mirroring the real
// shape this check exists for: a Parameters-side nested reference struct
// (GadgetOwnerRef) whose Observation-only variant (GadgetOwnerRefObservation)
// excludes the input-only *Ref field, exactly like
// SensitiveDataPolicyDataTypeRef / SensitiveDataPolicyDataTypeRefObservation
// in provider-f5xc. GadgetWidget has no matching *Observation companion at
// all, standing in for a nested type this checker cannot resolve.
const gadgetTypesSrc = `// Code generated by openapi2crd. DO NOT EDIT.
package v1alpha1

// GadgetOwnerRef is a compound cross-resource reference.
type GadgetOwnerRef struct {
	Name *string ` + "`json:\"name,omitempty\"`" + `
	OwnerRef *xpv1.Reference ` + "`json:\"ownerRef,omitempty\"`" + `
}

// GadgetOwnerRefObservation is the Observation-only variant of GadgetOwnerRef
// with cross-resource reference fields excluded — input-only, no observed
// state.
type GadgetOwnerRefObservation struct {
	Name *string ` + "`json:\"name,omitempty\"`" + `
}

// GadgetWidget has no Observation companion declared anywhere in this file.
type GadgetWidget struct {
	Label *string ` + "`json:\"label,omitempty\"`" + `
}

// GadgetParameters are the configurable fields of a Gadget.
type GadgetParameters struct {
	Comment *string ` + "`json:\"comment,omitempty\"`" + `
	Owners []GadgetOwnerRef ` + "`json:\"owners\"`" + `
	Widgets []GadgetWidget ` + "`json:\"widgets\"`" + `
}
`

const kindGadget = "Gadget"

// gadgetFixture writes the gadget types fixture once and returns both its
// path and the parsed GadgetParameters fields, so every test below resolves
// nested Observation structs against the exact same file its FieldInfo.GoType
// values were parsed from.
func gadgetFixture(t *testing.T) (path string, fields []FieldInfo) {
	t.Helper()
	path = writeFixture(t, "gadget_types.go", gadgetTypesSrc)
	fields, err := ParseGoTypes(path, kindGadget)
	if err != nil {
		t.Fatalf("ParseGoTypes: %v", err)
	}
	return path, fields
}

// TestCheckObservabilityRefFormNoExpectFlagged is the core regression case:
// a list-of-objects value patches to the reference-only shape with no
// expect:, and the compound reference's Ref field can never appear in the
// generated Observation struct.
func TestCheckObservabilityRefFormNoExpectFlagged(t *testing.T) {
	path, fields := gadgetFixture(t)

	tests := []manifest.UpdateTest{
		{
			Field: "owners",
			Value: []interface{}{
				map[string]interface{}{
					"ownerRef": map[string]interface{}{"name": "foo"},
				},
			},
		},
	}

	findings := CheckObservability(path, fields, tests)
	if len(findings) != 1 {
		t.Fatalf("got %d findings, want 1: %+v", len(findings), findings)
	}
	if findings[0].Field != "owners" {
		t.Errorf("Field = %q, want %q", findings[0].Field, "owners")
	}
	if len(findings[0].Keys) != 1 || findings[0].Keys[0] != "ownerRef" {
		t.Errorf("Keys = %v, want [ownerRef]", findings[0].Keys)
	}
}

