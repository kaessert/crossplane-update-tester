// TestStructElemType covers the Go-type-string classifier in isolation: the
// []/* wrapper stripping, and the builtin/cross-package/map exclusions.
func TestStructElemType(t *testing.T) {
	cases := map[string]struct {
		reason   string
		goType   string
		wantName string
		wantOK   bool
	}{
		"SliceOfLocalStruct": {
			reason:   "a []LocalStruct field resolves to LocalStruct",
			goType:   "[]GadgetOwnerRef",
			wantName: "GadgetOwnerRef",
			wantOK:   true,
		},
		"PointerToLocalStruct": {
			reason:   "a *LocalStruct field resolves to LocalStruct",
			goType:   "*GadgetOwnerRef",
			wantName: "GadgetOwnerRef",
			wantOK:   true,
		},
		"PlainString": {
			reason:   "a builtin scalar (lowercase) is never a resolvable struct",
			goType:   "string",
			wantName: "",
			wantOK:   false,
		},
		"PointerString": {
			reason:   "*string strips to the builtin scalar string, still not resolvable",
			goType:   "*string",
			wantName: "",
			wantOK:   false,
		},
		"SliceOfString": {
			reason:   "[]string strips to the builtin scalar string, still not resolvable",
			goType:   "[]string",
			wantName: "",
			wantOK:   false,
		},
		"CrossPackageType": {
			reason:   "a dotted cross-package type cannot be inspected locally",
			goType:   "*xpv2.NamespacedReference",
			wantName: "",
			wantOK:   false,
		},
		"MapType": {
			reason:   "a map's keys are data, not a fixed struct shape",
			goType:   "map[string]string",
			wantName: "",
			wantOK:   false,
		},
		"Empty": {
			reason:   "an empty GoType (e.g. an unpopulated FieldInfo literal in a test) resolves to nothing",
			goType:   "",
			wantName: "",
			wantOK:   false,
		},
	}

	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			gotName, gotOK := structElemType(tc.goType)
			if gotName != tc.wantName || gotOK != tc.wantOK {
				t.Errorf("%s: structElemType(%q) = (%q, %v), want (%q, %v)",
					tc.reason, tc.goType, gotName, gotOK, tc.wantName, tc.wantOK)
			}
		})
	}
}
