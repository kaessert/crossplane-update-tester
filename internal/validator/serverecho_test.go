// TestDiscoverServerEchoedMembers covers the discovery step in isolation:
// both registrations resolve to their struct's full field-name set plus the
// one field each clears.
func TestDiscoverServerEchoedMembers(t *testing.T) {
	dir := t.TempDir()
	writeFixtureInDir(t, dir, "httploadbalancer.go", serverEchoControllerSrc)

	members, err := discoverServerEchoedMembers(dir)
	if err != nil {
		t.Fatalf("discoverServerEchoedMembers: %v", err)
	}
	if len(members) != 2 {
		t.Fatalf("got %d members, want 2: %+v", len(members), members)
	}

	byEchoedField := make(map[string]ServerEchoedMember, len(members))
	for _, m := range members {
		byEchoedField[m.EchoedField] = m
	}

	invertMatch, ok := byEchoedField["InvertMatch"]
	if !ok {
		t.Fatalf("no member for InvertMatch: %+v", members)
	}
	wantHeaderFields := []string{"Exact", "InvertMatch", "Name", "Presence", "Regex"}
	sort.Strings(invertMatch.StructFieldNames)
	if !reflect.DeepEqual(invertMatch.StructFieldNames, wantHeaderFields) {
		t.Errorf("InvertMatch member StructFieldNames = %v, want %v", invertMatch.StructFieldNames, wantHeaderFields)
	}

	description, ok := byEchoedField["Description"]
	if !ok {
		t.Fatalf("no member for Description: %+v", members)
	}
	wantMetaFields := []string{"Description", "Name"}
	sort.Strings(description.StructFieldNames)
	if !reflect.DeepEqual(description.StructFieldNames, wantMetaFields) {
		t.Errorf("Description member StructFieldNames = %v, want %v", description.StructFieldNames, wantMetaFields)
	}
}

