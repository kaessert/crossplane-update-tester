// TestMatchServerEchoedMembersRequiresFullFieldSet covers the matcher in
// isolation: a candidate struct missing even one of a member's declared
// StructFieldNames is never matched, however many of the OTHER fields
// (including the echoed field's own name) it does share.
func TestMatchServerEchoedMembersRequiresFullFieldSet(t *testing.T) {
	members := []ServerEchoedMember{
		{StructFieldNames: []string{"Description", "Name"}, EchoedField: "Description"},
	}

	cases := map[string]struct {
		reason     string
		candidate  []FieldInfo
		wantEchoed bool
	}{
		"ExactFieldSetMatches": {
			reason:     "candidate declares exactly Description and Name",
			candidate:  []FieldInfo{{GoName: "Description"}, {GoName: "Name"}},
			wantEchoed: true,
		},
		"SupersetFieldSetMatches": {
			reason:     "candidate declares Description and Name plus CRD-only extras",
			candidate:  []FieldInfo{{GoName: "Description"}, {GoName: "Name"}, {GoName: "CertificateUrl"}},
			wantEchoed: true,
		},
		"MissingDeclaredFieldNeverMatches": {
			reason:     "candidate has Description but lacks Name — a different struct shape entirely",
			candidate:  []FieldInfo{{GoName: "Description"}, {GoName: "CertificateUrl"}},
			wantEchoed: false,
		},
	}

	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got := matchServerEchoedMembers(tc.candidate, members)
			if got["Description"] != tc.wantEchoed {
				t.Errorf("%s: matchServerEchoedMembers()[\"Description\"] = %v, want %v", tc.reason, got["Description"], tc.wantEchoed)
			}
		})
	}
}

